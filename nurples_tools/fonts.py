from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re
import shutil
import xml.etree.ElementTree as ET


FONT_BUFFER_BASE = 64_000
FONT_DIR = "fonts"
RUNTIME_FONT_NAMES = ("Lat38-VGA8_8x8.font",)


@dataclass(frozen=True)
class FontAsset:
    path: Path
    metadata_path: Path
    width: int
    height: int

    @property
    def label(self) -> str:
        return re.sub(r"[^A-Za-z0-9_]", "_", self.path.stem)


def _metadata_values(metadata_path: Path) -> dict[str, str]:
    root = ET.parse(metadata_path).getroot()
    return {
        setting.attrib["name"]: setting.attrib["value"]
        for setting in root.findall("setting")
    }


def discover_fonts(source_dir: Path) -> list[FontAsset]:
    source_dir = source_dir.resolve()
    font_paths = [source_dir / name for name in RUNTIME_FONT_NAMES]
    missing = [path.name for path in font_paths if not path.is_file()]
    metadata_paths = [Path(f"{font_path}.xml") for font_path in font_paths]
    missing.extend(path.name for path in metadata_paths if not path.is_file())
    if missing:
        raise ValueError(f"missing runtime font assets: {', '.join(missing)}")

    if FONT_BUFFER_BASE + len(font_paths) > 65_536:
        raise ValueError("vendored fonts exceed the 16-bit buffer ID range")

    fonts = []
    for font_path in font_paths:
        metadata_path = Path(f"{font_path}.xml")
        values = _metadata_values(metadata_path)
        try:
            width = int(values["font_width_mod"])
            height = int(values["font_height_mod"])
        except (KeyError, ValueError) as error:
            raise ValueError(
                f"invalid dimensions in {metadata_path.name}"
            ) from error
        if width <= 0 or height <= 0:
            raise ValueError(f"non-positive dimensions in {metadata_path.name}")
        fonts.append(FontAsset(font_path, metadata_path, width, height))
    return fonts


def render_fonts_manifest(fonts: list[FontAsset]) -> str:
    lines = [
        "; Generated by build_fonts.py; do not edit.\n",
        "font_list_record_size: equ 12\n",
        "font_list_width: equ 0\n",
        "font_list_height: equ 3\n",
        "font_list_bufferId: equ 6\n",
        "font_list_filename: equ 9\n\n",
        f"num_fonts: equ {len(fonts)}\n\n",
        "; Index list:\n",
    ]
    for index, font in enumerate(fonts, start=FONT_BUFFER_BASE):
        lines.append(f"{font.label}: equ {index}\n")

    lines.extend(("\n", "font_list: ; width; height; bufferId; filename;:\n"))
    for index, font in enumerate(fonts, start=FONT_BUFFER_BASE):
        lines.append(
            f"\tdl {font.width}, {font.height}, {index}, fn_{font.label}\n"
        )

    lines.extend(("\n", "; files_list: ; filename:\n"))
    for font in fonts:
        lines.append(
            f'fn_{font.label}: db "{FONT_DIR}/{font.path.name}",0\n'
        )
    return "".join(lines)


def sync_fonts(fonts: list[FontAsset], target_dir: Path) -> None:
    target_dir.mkdir(parents=True, exist_ok=True)
    expected_names = {font.path.name for font in fonts}
    for existing_path in target_dir.iterdir():
        if (
            existing_path.is_file()
            and existing_path.name.endswith((".font", ".font.xml"))
            and existing_path.name not in expected_names
        ):
            existing_path.unlink()

    for font in fonts:
        shutil.copy2(font.path, target_dir / font.path.name)


def build_fonts(source_dir: Path, target_dir: Path, manifest_path: Path) -> None:
    fonts = discover_fonts(source_dir)
    sync_fonts(fonts, target_dir)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(render_fonts_manifest(fonts), encoding="utf-8")


def check_fonts(source_dir: Path, target_dir: Path, manifest_path: Path) -> list[str]:
    fonts = discover_fonts(source_dir)
    errors = []
    expected_names = {font.path.name for font in fonts}
    if target_dir.is_dir():
        actual_names = {
            path.name
            for path in target_dir.iterdir()
            if path.is_file() and path.name.endswith((".font", ".font.xml"))
        }
    else:
        actual_names = set()
    if actual_names != expected_names:
        errors.append("tgt/fonts file set differs from vendored assets")

    for font in fonts:
        target_path = target_dir / font.path.name
        if (
            not target_path.is_file()
            or target_path.read_bytes() != font.path.read_bytes()
        ):
            errors.append(f"target differs: {target_path}")

    expected_manifest = render_fonts_manifest(fonts)
    if (
        not manifest_path.is_file()
        or manifest_path.read_text(encoding="utf-8") != expected_manifest
    ):
        errors.append(f"manifest differs: {manifest_path}")
    return errors
