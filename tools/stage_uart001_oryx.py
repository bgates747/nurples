#!/usr/bin/env python3
"""Create a stopped, hash-pinned Oryx Flexe profile for UART-001.

This is deployment only. It never builds the fixture and never starts an
emulator. Run it on Oryx after transferring a completed project tree.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROFILE = PROJECT_ROOT / ".emulator/uart001-rc3"
DEFAULT_TEMPLATE = (
    Path.home()
    / "Agon/mystuff/eirene-mos/.emulator/rc003-r01/rc3-jit"
)
CARD_SIZE = 32 * 1024 * 1024
RC3_COMMIT = "97311c437093e416342a6c836cf9914f2ced027d"
RC3_RUNTIME_SHA256 = {
    "flexe-agon-emulator.bin": (
        "7e7d0e1bc89af72bde7ffbd6c06446aaefda4d1803f89eb1faf3167307ee1e01"
    ),
    "flexe-vdp.so": (
        "0866265bd6f3d73ad572f31dc1bb954f308ed9a5d857efa9414d37e1ade13374"
    ),
    "esp32-firmware.bin": (
        "201ad8ab4af807c261cb92634286b2fbaedcf3879f140e820b60ab54cf707e2a"
    ),
    "esp32-firmware.elf": (
        "14715f9f3d88d891dfddbf77c1423defffdb2351412f44fdce140b6d28f59470"
    ),
    "mos_platform.bin": (
        "d7a51147f3381cd68d56f3fbe4605434a897dfae1b049269afeba09ec2b7eb50"
    ),
    "mos_platform.map": (
        "48dae5890af7b49fe6bcb535a20e9b6432069c8d84666e3d0e8e7e1070282be9"
    ),
}
FIXTURE_FILES = (
    "nurples-uart001.bin",
    "nurples-uart001.symbols",
    "game.agnb",
    "ui.agnb",
)
GUEST_ROOT = "mystuff/nurples-dev/tests/uart001"
AUTOEXEC = (
    b"SET KEYBOARD 1\r\n"
    b"cd /mystuff/nurples-dev/tests/uart001\r\n"
    b"load nurples-uart001.bin\r\n"
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def require_file(path: Path, label: str) -> Path:
    if path.is_symlink():
        try:
            resolved = path.resolve(strict=True)
        except OSError as error:
            raise SystemExit(f"Broken {label} symlink: {path}") from error
        if not resolved.is_file():
            raise SystemExit(f"{label} does not resolve to a file: {path}")
        return path
    if not path.is_file():
        raise SystemExit(f"Missing {label}: {path}")
    return path


def run(*command: str, cwd: Path | None = None) -> None:
    subprocess.run(command, cwd=cwd, check=True)


def make_card_directory(card: Path, relative: str) -> None:
    current: list[str] = []
    for part in Path(relative).parts:
        current.append(part)
        destination = "::/" + "/".join(current)
        probe = subprocess.run(
            ["mdir", "-i", str(card), destination],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
        if probe.returncode != 0:
            run("mmd", "-i", str(card), destination)


def verify_template(template: Path) -> None:
    for name, expected in RC3_RUNTIME_SHA256.items():
        path = require_file(template / name, f"RC3 runtime input {name}")
        actual = sha256(path)
        if actual != expected:
            raise SystemExit(
                f"RC3 runtime identity mismatch for {path}: "
                f"expected {expected}, got {actual}"
            )
    launcher = require_file(template / "flexe-agon-emulator", "RC3 launcher")
    marker = require_file(template / ".bespoke-vdp-profile", "VDP marker")
    if marker.read_text(encoding="utf-8").strip() != "flexe-vdp.so":
        raise SystemExit(f"Unexpected RC3 VDP marker: {marker}")
    text = launcher.read_text(encoding="utf-8")
    required = (
        "# Generated by agon-dev-env setup_emulator.py.",
        "--sdcard-img",
        "AGON_FLEXE_ENGINE",
        "sha256sum --check --status .runtime.sha256",
    )
    if any(value not in text for value in required):
        raise SystemExit(f"RC3 launcher lacks required guards: {launcher}")


def verify_project_inputs(project: Path) -> dict[str, str]:
    target = project / "tgt"
    files = [require_file(target / name, f"fixture input {name}") for name in FIXTURE_FILES]
    fonts = target / "fonts"
    if fonts.is_symlink() or not fonts.is_dir():
        raise SystemExit(f"Missing regular fixture font directory: {fonts}")
    font_files = sorted(path for path in fonts.rglob("*") if path.is_file())
    if not font_files or any(path.is_symlink() for path in font_files):
        raise SystemExit(f"Fixture fonts are empty or contain links: {fonts}")
    return {
        path.relative_to(project).as_posix(): sha256(path)
        for path in (*files, *font_files)
    }


def copy_runtime(template: Path, profile: Path) -> None:
    for name in RC3_RUNTIME_SHA256:
        shutil.copy2(template / name, profile / name, follow_symlinks=True)
    launcher_text = (template / "flexe-agon-emulator").read_text(encoding="utf-8")
    launcher_text = launcher_text.replace(
        "FSIM runtime identity mismatch",
        "Nurples UART-001 runtime identity mismatch",
    )
    launcher = profile / "flexe-agon-emulator"
    launcher.write_text(launcher_text, encoding="utf-8")
    launcher.chmod(0o755)
    (profile / ".bespoke-vdp-profile").write_text(
        "flexe-vdp.so\n", encoding="utf-8"
    )
    (profile / ".mos-release").write_text(
        "3.1.0_uart0_rc_3 "
        f"{RC3_COMMIT}; Nurples UART-001; emulator qualification only\n",
        encoding="utf-8",
    )
    (profile / ".mos-release.sha256").write_text(
        "".join(
            f"{RC3_RUNTIME_SHA256[name]}  {name}\n"
            for name in ("mos_platform.bin", "mos_platform.map")
        ),
        encoding="utf-8",
    )


def build_card(project: Path, profile: Path) -> None:
    card = profile / "card.img"
    with card.open("xb") as stream:
        stream.truncate(CARD_SIZE)
    run("mkfs.fat", "-F", "16", str(card))
    make_card_directory(card, GUEST_ROOT)
    for name in FIXTURE_FILES:
        run(
            "mcopy",
            "-i",
            str(card),
            str(project / "tgt" / name),
            f"::/{GUEST_ROOT}/{name}",
        )
    fonts = project / "tgt/fonts"
    make_card_directory(card, f"{GUEST_ROOT}/fonts")
    for source in sorted(fonts.rglob("*")):
        relative = source.relative_to(fonts)
        destination = f"{GUEST_ROOT}/fonts/{relative.as_posix()}"
        if source.is_dir():
            make_card_directory(card, destination)
        else:
            run(
                "mcopy",
                "-i",
                str(card),
                str(source),
                f"::/{destination}",
            )
    autoexec = profile / "autoexec.txt"
    autoexec.write_bytes(AUTOEXEC)
    run("mcopy", "-i", str(card), str(autoexec), "::/autoexec.txt")
    (profile / "sdcard").mkdir()
    (profile / "sdcard.img").symlink_to("card.img")


def write_identity(
    profile: Path,
    template: Path,
    source_hashes: dict[str, str],
) -> None:
    runtime_names = (*RC3_RUNTIME_SHA256, "flexe-agon-emulator")
    runtime_hashes = {name: sha256(profile / name) for name in runtime_names}
    (profile / ".runtime.sha256").write_text(
        "".join(f"{runtime_hashes[name]}  {name}\n" for name in runtime_names),
        encoding="utf-8",
    )
    identity = {
        "schema": 1,
        "project": "nurples-dev",
        "fixture": "UART-001",
        "firmware_tag": "3.1.0_uart0_rc_3",
        "firmware_commit": RC3_COMMIT,
        "template": str(template),
        "guest_root": f"/{GUEST_ROOT}",
        "autoexec_runs_fixture": False,
        "source_sha256": source_hashes,
        "runtime_sha256": runtime_hashes,
        "card_sha256": sha256(profile / "card.img"),
        "stopped": True,
    }
    (profile / "identity.json").write_text(
        json.dumps(identity, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    run("sha256sum", "--check", "--status", ".mos-release.sha256", cwd=profile)
    run("sha256sum", "--check", "--status", ".runtime.sha256", cwd=profile)
    run("bash", "-n", "flexe-agon-emulator", cwd=profile)
    run("mdir", "-i", str(profile / "card.img"), f"::/{GUEST_ROOT}")


def stage(project: Path, template: Path, profile: Path) -> Path:
    project = project.expanduser().resolve(strict=True)
    template = template.expanduser().resolve(strict=True)
    profile = profile.expanduser().resolve(strict=False)
    if profile.exists() or profile.is_symlink():
        raise SystemExit(f"Refusing to replace existing profile: {profile}")
    profile.parent.mkdir(parents=True, exist_ok=True)
    verify_template(template)
    source_hashes = verify_project_inputs(project)
    staging = Path(
        tempfile.mkdtemp(prefix=f".{profile.name}-", dir=profile.parent)
    )
    try:
        copy_runtime(template, staging)
        build_card(project, staging)
        write_identity(staging, template, source_hashes)
        os.replace(staging, profile)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return profile


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=PROJECT_ROOT)
    parser.add_argument("--template", type=Path, default=DEFAULT_TEMPLATE)
    parser.add_argument("--profile", type=Path, default=DEFAULT_PROFILE)
    args = parser.parse_args()
    profile = stage(args.project, args.template, args.profile)
    print(f"Stopped UART-001 profile: {profile}")
    print(f"Launch only after Oryx checkout: cd {profile} && ./flexe-agon-emulator")


if __name__ == "__main__":
    main()
